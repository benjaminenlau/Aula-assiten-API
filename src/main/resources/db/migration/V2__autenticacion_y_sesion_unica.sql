CREATE TABLE usuario_app (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario VARCHAR(60) NOT NULL UNIQUE,
    nombre VARCHAR(160) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(20) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    intentos_fallidos INTEGER NOT NULL DEFAULT 0,
    bloqueado_hasta TIMESTAMP WITH TIME ZONE,
    creado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT usuario_app_usuario_valido CHECK (usuario ~ '^[a-z0-9._-]{3,60}$'),
    CONSTRAINT usuario_app_nombre_valido CHECK (length(btrim(nombre)) BETWEEN 1 AND 160),
    CONSTRAINT usuario_app_rol_valido CHECK (rol IN ('ADMIN', 'PROFESIONAL')),
    CONSTRAINT usuario_app_intentos_validos CHECK (intentos_fallidos BETWEEN 0 AND 5)
);

-- La clave primaria impide dos sesiones de un usuario, incluso entre instancias de la API.
-- El secreto del portador nunca se guarda: solamente su resumen SHA-256.
CREATE TABLE sesion_usuario (
    usuario_id BIGINT PRIMARY KEY REFERENCES usuario_app (id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL UNIQUE,
    creada_en TIMESTAMP WITH TIME ZONE NOT NULL,
    ultima_actividad TIMESTAMP WITH TIME ZONE NOT NULL,
    expira_en TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT sesion_usuario_hash_valido CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT sesion_usuario_expiracion_valida CHECK (expira_en > creada_en),
    CONSTRAINT sesion_usuario_actividad_valida CHECK (ultima_actividad >= creada_en)
);

CREATE INDEX idx_sesion_usuario_expiracion ON sesion_usuario (expira_en);

-- Contador compartido por todas las instancias; la clave es el hash de la dirección remota.
CREATE TABLE limite_login (
    clave CHAR(64) PRIMARY KEY,
    ventana TIMESTAMP WITH TIME ZONE NOT NULL,
    intentos INTEGER NOT NULL CHECK (intentos > 0)
);

CREATE INDEX idx_limite_login_ventana ON limite_login (ventana);
