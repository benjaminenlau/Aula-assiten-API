-- Compatible con PostgreSQL 16. Intervalos semiabiertos: [inicio, fin).
CREATE EXTENSION IF NOT EXISTS btree_gist WITH SCHEMA public;

CREATE TABLE espacio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(255) NOT NULL,
    CONSTRAINT pk_espacio PRIMARY KEY (id)
);

CREATE TABLE docente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(255) NOT NULL,
    CONSTRAINT pk_docente PRIMARY KEY (id)
);

CREATE TABLE asignacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    espacio_id BIGINT NOT NULL,
    docente_id BIGINT NOT NULL,
    inicio TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    fin TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT pk_asignacion PRIMARY KEY (id),
    CONSTRAINT fk_asignacion_espacio FOREIGN KEY (espacio_id) REFERENCES espacio (id),
    CONSTRAINT fk_asignacion_docente FOREIGN KEY (docente_id) REFERENCES docente (id),
    CONSTRAINT intervalo_valido CHECK (inicio < fin),
    CONSTRAINT no_cruce_espacio EXCLUDE USING gist (
        espacio_id WITH =,
        tsrange(inicio, fin, '[)') WITH &&
    ),
    CONSTRAINT no_cruce_docente EXCLUDE USING gist (
        docente_id WITH =,
        tsrange(inicio, fin, '[)') WITH &&
    )
);
